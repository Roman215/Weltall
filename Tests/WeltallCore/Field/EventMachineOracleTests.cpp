	constexpr int32 Ticks = 40;
	/** The state's status bit for movement bounds: they follow the state in the digest. */
	constexpr uint32 MoveBoundsSet = 0x1000;

	/**
	 * Records the actors given sprites; each sprite stands in for one whose first frame is 0x28 texels
	 * tall, as the oracle's does. In the moves' scenarios each actor also has a sprite of its own
	 * without a file, whose speed the walks and glides set.
	 */
	class FRecordingModels final : public IFieldActorModels
	{
	public:
		std::optional<FFieldSpriteResult> LoadSprite(const FFieldSpriteRequest& Request) override
		{
			Actors.push_back(static_cast<uint8>(Request.Actor));
			return FFieldSpriteResult{0x28, false};
		}

		FSprite* ActorSprite(int32 Actor) override { return Actor >= 0 && static_cast<std::size_t>(Actor) < StandIns.size() ? &StandIns[static_cast<std::size_t>(Actor)] : nullptr; }
		FSpriteSystem* SpriteSystem() override { return nullptr; }
		void SwapSprites(int32, int32) override {}
		bool LoadExtraAnimations(int32, int32) override { return true; }
		void UseExtraAnimations(int32) override {}

		std::vector<uint8> Actors;
		std::vector<FSprite> StandIns;
	};

	void AddWord(std::vector<uint8>& Bytes, uint32 Value, int32 Size)
	{
		for (int32 Byte = 0; Byte < Size; ++Byte)
		{
			Bytes.push_back(static_cast<uint8>(Value >> (8 * Byte)));
		}
	}

	/** The particle emitters' setup in the original's layout, with FE 8F's and FE 90's words after it. */
	void AddParticleSetup(std::vector<uint8>& Bytes, const FFieldParticles& Particles)
	{
		for (const FFieldParticleEmitter& Emitter : Particles.Setup)
		{
			for (const int16 Value : {Emitter.Word00, Emitter.Delay, Emitter.EmitTicks, Emitter.Count})
			{
				AddWord(Bytes, static_cast<uint16>(Value), 2);
			}
			AddWord(Bytes, static_cast<uint32>(Emitter.Speed), 4);
			for (const std::array<int16, 3>& Triple : {Emitter.Origin, Emitter.Target, Emitter.Acceleration})
			{
				for (const int16 Value : Triple)
				{
					AddWord(Bytes, static_cast<uint16>(Value), 2);
				}
				AddWord(Bytes, 0, 2);
			}
			for (const int16 Value : {Emitter.SpeedScale, Emitter.SpawnRadius, Emitter.TargetSpread})
			{
				AddWord(Bytes, static_cast<uint16>(Value), 2);
			}
			AddWord(Bytes, Emitter.Flags, 2);
			AddWord(Bytes, 0, 4);
			for (const std::array<int16, 2>& Offset : Emitter.FacingOffsets)
			{
				AddWord(Bytes, static_cast<uint16>(Offset[0]), 2);
				AddWord(Bytes, static_cast<uint16>(Offset[1]), 2);
			}
			for (const int16 Value : {Emitter.Scale, Emitter.Owner, Emitter.Sprite, Emitter.Interval, Emitter.Lifetime})
			{
				AddWord(Bytes, static_cast<uint16>(Value), 2);
			}
			for (const std::array<int16, 3>& Triple : {Emitter.Size, Emitter.SizeStep})
			{
				for (const int16 Value : Triple)
				{
					AddWord(Bytes, static_cast<uint16>(Value), 2);
				}
				AddWord(Bytes, 0, 2);
			}
			Bytes.insert(Bytes.end(), Emitter.Color.begin(), Emitter.Color.end());
			Bytes.push_back(0);
			for (const int8 Value : Emitter.ColorStep)
			{
				Bytes.push_back(static_cast<uint8>(Value));
			}
			Bytes.push_back(0);
			for (const int16 Value : {Emitter.GearSlot, Emitter.GearJoint, Emitter.Roll})
			{
				AddWord(Bytes, static_cast<uint16>(Value), 2);
			}
		}
		for (const int32 Value : {Particles.Owner, Particles.SpaceBits, Particles.GearSlot, Particles.GearJoint, Particles.Current})
		{
			AddWord(Bytes, static_cast<uint32>(Value), 4);
		}
	}

	/**
	 * Records the scripts' sound effects as the oracle records the sound driver's calls: a stop, a play,
	 * a channel's volume, pan or fade, or the playing tracks asked for, which are the scenario's until
	 * each answer lets the lowest of them end.
	 */
	class FRecordingSoundEffects final : public IFieldSoundEffects
	{
	public:
		void StopEffectOn(int32 Channel) override { Record(0, {static_cast<uint32>(Channel)}); }

		void PlayEffectOn(uint32 Effect, int32 Channel, int32 Volume, int32 Pan) override
		{
			Record(1, {Effect, static_cast<uint32>(Channel), static_cast<uint32>(Volume), static_cast<uint32>(Pan)});
		}

		void SetEffectVolumeOn(int32 Channel, int32 Volume) override { Record(8, {static_cast<uint32>(Channel), static_cast<uint32>(Volume)}); }
		void SetEffectPanOn(int32 Channel, int32 Pan) override { Record(9, {static_cast<uint32>(Channel), static_cast<uint32>(Pan)}); }

		void FadeEffectVolumeOn(int32 Channel, int32 Volume, int32 SlideTicks) override
		{
			Record(10, {static_cast<uint32>(Channel), static_cast<uint32>(Volume), static_cast<uint32>(SlideTicks)});
		}

		uint32 PlayingEffects() override
		{
			const uint32 Answer = Playing;
			Record(7, {Answer});
			Playing &= Playing - 1;
			return Answer;
		}

		std::vector<uint8> Calls;
		uint32 Playing = 0;

	private:
		void Record(uint32 Kind, std::initializer_list<uint32> Values)
		{
			AddWord(Calls, Kind, 1);
			for (const uint32 Value : Values)
			{
				AddWord(Calls, Value, 4);
			}
		}
	};

	/** Records the scripts' changes to the playing song beside the sound effects, as the oracle records the driver's calls. */
	class FRecordingSongs final : public Testing::FFieldSongsModel
	{
	public:
		explicit FRecordingSongs(std::vector<uint8>& InCalls) : Calls(InCalls) {}

		void SetMusicVolume(int32 Volume, int32 Interrupts) override { Record(2, {static_cast<uint32>(Volume), static_cast<uint32>(Interrupts)}); }
		void SetMusicPitch(int32 Semitones, int32 Interrupts) override { Record(3, {static_cast<uint32>(Semitones), static_cast<uint32>(Interrupts)}); }
		void SetMusicTempo(int32 Scale, int32 Interrupts) override { Record(4, {static_cast<uint32>(Scale), static_cast<uint32>(Interrupts)}); }
		void SetMusicPan(int32 Offset, int32 Interrupts) override { Record(5, {static_cast<uint32>(Offset), static_cast<uint32>(Interrupts)}); }
		void MuteMusicTracks(uint32 Mask) override { Record(6, {Mask}); }

	private:
		void Record(uint32 Kind, std::initializer_list<uint32> Values)
		{
			AddWord(Calls, Kind, 1);
			for (const uint32 Value : Values)
			{
				AddWord(Calls, Value, 4);
			}
		}

		std::vector<uint8>& Calls;
	};

	/** What the scripts ask of the field's main loop, in the original's words' order and widths. */
	void AddRequests(std::vector<uint8>& Bytes, const FEventContext& Context)
	{
		const FEventRequests& Requests = Context.Requests;
		AddWord(Bytes, Requests.bProgram ? 0 : 0xFFFFFFFF, 4);
		AddWord(Bytes, static_cast<uint32>(Requests.Program), 4);
		AddWord(Bytes, Requests.bBattling ? 0 : 0xFFFFFFFF, 4);
		for (const uint8 Byte : Requests.BattlingParameters)
		{
			AddWord(Bytes, Byte, 1);
		}
		AddWord(Bytes, Requests.bLeavingField ? 1 : 0, 4);
		AddWord(Bytes, Context.MenuRequest, 4);
		AddWord(Bytes, Context.MenuProgramParam, 1);
		AddWord(Bytes, static_cast<uint32>(Context.MenusPending), 4);
		AddWord(Bytes, Requests.bMovie ? 1 : 0, 4);
		const FFieldMovieRequest& Movie = Requests.Movie;
		AddWord(Bytes, Movie.Movie, 2);
		for (const int16 Value : Movie.Buffers)
		{
			AddWord(Bytes, static_cast<uint16>(Value), 2);
		}
		for (const uint16 Value : {Movie.StartSector, Movie.StartFrame, Movie.EndFrame, Movie.Kind, static_cast<uint16>(Movie.Width), static_cast<uint16>(Movie.Height),
				 static_cast<uint16>(Movie.bTrueColour ? 1 : 0), Movie.Cues, static_cast<uint16>(Movie.bRewinds ? 1 : 0)})
		{
			AddWord(Bytes, Value, 2);
		}
		AddWord(Bytes, Movie.Flags, 4);
		AddWord(Bytes, Context.Movie.bStarted ? 1 : 0, 4);
		AddWord(Bytes, static_cast<uint32>(Context.Movie.StopRequests), 4);
		AddWord(Bytes, static_cast<uint32>(Context.Movie.Frame), 4);
		AddWord(Bytes, Context.ReturnFade, 4);
		AddWord(Bytes, Requests.Dissolve, 4);
		AddWord(Bytes, static_cast<uint32>(Requests.DissolveTicks), 4);
		AddWord(Bytes, Context.PauseDisabled, 1);
		AddWord(Bytes, Requests.bBattleNamesNextMap ? 1 : 0, 4);
		AddWord(Bytes, Context.bFrameVariablesFrozen ? 1 : 0, 1);
		AddWord(Bytes, static_cast<uint32>(Requests.MapTransition), 4);
		AddWord(Bytes, static_cast<uint32>(Requests.MapTransitionTicks), 4);
		AddWord(Bytes, Requests.BattleKind, 1);
		AddWord(Bytes, static_cast<uint32>(Context.MovieView), 4);
		AddWord(Bytes, static_cast<uint32>(Context.MapNumber), 4);
	}

	void AddSnapshot(FSha1& Hash, const FEventContext& Context, const FPsxRandom& Random, const FGameState& Game, const Testing::FFieldSongsModel& Songs, const FRecordingModels& Models,
		const FRecordingSoundEffects& Sounds)
	{
		std::vector<uint8> Bytes;
		for (uint32 Address = 0; Address < FEventVariables::AddressEnd; Address += 2)
		{
			const uint16 Value = Context.Variables.Raw(Address);
			Bytes.push_back(static_cast<uint8>(Value));
			Bytes.push_back(static_cast<uint8>(Value >> 8));
		}
		for (const FEventActorState& State : Context.States)
		{
			const auto Layout = Testing::ToOriginalLayout(State);
			Bytes.insert(Bytes.end(), Layout.begin(), Layout.end());
			if ((State.Status & MoveBoundsSet) != 0)
			{
				for (const int16 Value : State.MoveBounds)
				{
					AddWord(Bytes, static_cast<uint16>(Value), 2);
				}
			}
		}
		for (std::size_t Actor = 0; Actor < Context.States.size(); ++Actor)
		{
			const FFieldActor& Record = Context.Actors[Actor];
			for (const std::array<int16, 3>& Row : Record.Matrix)
			{
				for (const int16 Value : Row)
				{
					AddWord(Bytes, static_cast<uint16>(Value), 2);
				}
			}
			for (const int32 Value : Record.Translation)
			{
				AddWord(Bytes, static_cast<uint32>(Value), 4);
			}
			for (const int32 Value : Record.Position)
			{
				AddWord(Bytes, static_cast<uint32>(Value), 4);
			}
			for (const int16 Angle : Record.Rotation)
			{
				AddWord(Bytes, static_cast<uint16>(Angle), 2);
			}
			AddWord(Bytes, Record.Flags, 2);
			AddWord(Bytes, Record.DrawMode, 2);
		}
		AddWord(Bytes, Random.Seed(), 4);
		AddWord(Bytes, Context.PadLatched, 2);
		AddWord(Bytes, static_cast<uint32>(Context.Clock.Ticks), 4);
		AddWord(Bytes, Context.Clock.Mode, 4);
		Bytes.insert(Bytes.end(), Game.Block().begin(), Game.Block().end());
		const std::vector<uint8> Field = Testing::FieldStateBytes(Context, Songs);
		Bytes.insert(Bytes.end(), Field.begin(), Field.end());
		const FFieldControls& Controls = Context.Controls;
		const FFieldMovement& Movement = Context.Movement;
		AddWord(Bytes, static_cast<uint16>(Controls.StuckTicks), 2);
		for (const int16 Value : {Movement.ActionMode, Movement.JumpAnimation, Movement.JumpInterval, Movement.JumpCooldown})
		{
			AddWord(Bytes, static_cast<uint16>(Value), 2);
		}
		AddWord(Bytes, Controls.bReversed ? 1 : 0, 1);
		AddWord(Bytes, Controls.ScriptMask, 2);
		AddWord(Bytes, Controls.bFollowClose ? 1 : 0, 1);
		AddWord(Bytes, Context.bPlayerControlled ? 1 : 0, 4);
		AddWord(Bytes, Context.bBattleRequested ? 0 : 0xFFFFFFFF, 4);
		AddWord(Bytes, Context.Encounters.bBattleDrawn ? 1 : 0, 4);
		AddWord(Bytes, Context.Encounters.Formation, 1);
		for (const FSprite& Sprite : Models.StandIns)
		{
			for (const std::array<int32, 3>& Triple : {Sprite.Position, Sprite.Velocity})
			{
				for (const int32 Value : Triple)
				{
					AddWord(Bytes, static_cast<uint32>(Value), 4);
				}
			}
			AddWord(Bytes, static_cast<uint32>(Sprite.Speed), 4);
			AddWord(Bytes, static_cast<uint16>(Sprite.FloorY), 2);
		}
		for (const std::vector<FFieldVramOperation>* Operations : {&Context.Render.VramOperations, &Context.Render.LineScrollMoves})
		{
			for (const FFieldVramOperation& Operation : *Operations)
			{
				for (const int16 Value : {Operation.Rect.X, Operation.Rect.Y, Operation.Rect.Width, Operation.Rect.Height, Operation.ToX, Operation.ToY})
				{
					AddWord(Bytes, static_cast<uint16>(Value), 2);
				}
				AddWord(Bytes, Operation.Kind == EFieldVramChange::Clear ? 1 : 0, 1);
			}
		}
		Bytes.insert(Bytes.end(), Sounds.Calls.begin(), Sounds.Calls.end());
		AddParticleSetup(Bytes, Context.Particles);
		AddWord(Bytes, Context.Camera.FollowedActor, 2);
		const FFieldCamera& Camera = Context.Camera;
		AddWord(Bytes, static_cast<uint32>(Camera.TurnStep), 4);
		AddWord(Bytes, static_cast<uint16>(Camera.TurnTicks), 2);
		for (const int16 Angle : Camera.ScreenAngles)
		{
			AddWord(Bytes, static_cast<uint16>(Angle), 2);
		}
		AddWord(Bytes, Camera.bShaking ? 1 : 0, 2);
		AddWord(Bytes, static_cast<uint16>(Camera.ShakeTicks), 2);
		AddWord(Bytes, Camera.bShakeStops ? 1 : 0, 2);
		for (const FFieldPoint* Words : {&Camera.ShakeAmplitude, &Camera.ShakeGrowth})
		{
			for (const int32 Word : *Words)
			{
				AddWord(Bytes, static_cast<uint32>(Word), 4);
			}
		}
		for (std::size_t Actor = 0; Actor < Context.States.size(); ++Actor)
		{
			if ((Context.Actors[Actor].Flags & FieldActorFlag::VertexAnimation) != 0)
			{
				for (const int32 Value : Context.States[Actor].PartValues)
				{
					AddWord(Bytes, static_cast<uint32>(Value), 4);
				}
			}
		}
		const FFieldScreenWave& Wave = Context.Render.ScreenWave;
		for (const std::vector<uint8>& Part : {Testing::LineScrollBytes(Context.Render.LineScrolls), Testing::ScreenWaveBytes(Wave),
				 Wave.bDrawn ? Testing::ScreenWaveCellBytes(Wave) : std::vector<uint8>{}})
		{
			Bytes.insert(Bytes.end(), Part.begin(), Part.end());
		}
		AddWord(Bytes, static_cast<uint16>(Context.PartyWalkHurries), 2);
		AddWord(Bytes, Context.Controls.bLeaderApart ? 1 : 0, 2);
		AddWord(Bytes, Context.LeaderFlagsBeforeWalk, 4);
		AddWord(Bytes, Context.bPartyWalking ? 1 : 0, 1);
		AddWord(Bytes, Context.Controls.bPartyPlaced ? 1 : 0, 1);
		AddWord(Bytes, Context.LeaderActor, 4);
		const FFieldActorSounds& ActorSounds = Context.ActorSounds;
		for (const FFieldActorSoundChannel& Channel : ActorSounds.Channels)
		{
			AddWord(Bytes, Channel.Owner, 2);
			AddWord(Bytes, Channel.Sound, 2);
		}
		AddWord(Bytes, ActorSounds.Listener, 2);
		AddWord(Bytes, ActorSounds.KeepMask, 2);
		AddWord(Bytes, static_cast<uint16>(ActorSounds.Range), 2);
		AddWord(Bytes, Movement.FloorPushAngle, 2);
		AddWord(Bytes, static_cast<uint16>(Movement.FloorPushScale), 2);
		for (const int16 Angle : Camera.WorldAngles)
		{
			AddWord(Bytes, static_cast<uint16>(Angle), 2);
		}
		const FVramRect& Clip = Context.Render.DrawClip;
		for (const int32 Value : {int32{Clip.X}, int32{Clip.Y}, int32{Clip.Width}, int32{Clip.Height}, int32{Clip.X}, Clip.Y + 0x100, int32{Clip.Width},
				 int32{Clip.Height}})
		{
			AddWord(Bytes, static_cast<uint16>(Value), 2);
		}
		AddWord(Bytes, Context.Render.bHiResStill ? 1 : 0, 4);
		AddRequests(Bytes, Context);
		const FFieldGearLights& Lights = Context.Render.GearLights;
		for (const FFieldGearLights::FPointLight& Point : Lights.Points)
		{
			AddWord(Bytes, static_cast<uint16>(Point.Actor), 2);
		}
		for (const FFieldGearLights::FPointLight& Point : Lights.Points)
		{
			for (const std::array<int16, 3>* Color : {&Point.Near, &Point.Far})
			{
				for (const int16 Channel : *Color)
				{
					AddWord(Bytes, static_cast<uint16>(Channel), 2);
				}
			}
		}
		for (const FFieldGearLights::FPointLight& Point : Lights.Points)
		{
			AddWord(Bytes, static_cast<uint32>(Point.Radius), 4);
		}
		for (const FFieldGearLights::FPointLight& Point : Lights.Points)
		{
			for (const int16 Axis : Point.Position)
			{
				AddWord(Bytes, static_cast<uint16>(Axis), 2);
			}
		}
		Hash.Update(Bytes);
	}

	std::string RunScenario(uint32 Seed, const FGteArctangents& Arctangents, Testing::EEventScenarioFamily Family)
	{
		const Testing::FEventScenario Scenario = Testing::GenerateEventScenario(Seed, Family);
		const auto Scripts = FEventScripts::Parse(Scenario.Section);
		REQUIRE(Scripts);
		FFieldWalkmesh Walkmesh = Scenario.Walkmesh;
		FPsxRandom Random(Scenario.RandomSeed);
		FGameState Game;
		std::copy(Scenario.GameState.begin(), Scenario.GameState.end(), Game.Block().begin());
		FRecordingModels Models;
		if (Scenario.bStandInSprites)
		{
			Models.StandIns.resize(Scenario.States.size());
			for (std::size_t Actor = 0; Actor < Models.StandIns.size(); ++Actor)
			{
				Models.StandIns[Actor].Gravity = Scenario.StandInGravity[Actor];
			}
		}
		FRecordingSoundEffects Sounds;
		Sounds.Playing = Scenario.PlayingEffects;
		FRecordingSongs Songs(Sounds.Calls);
		Songs.bMusicLoaded = Scenario.bMusicLoaded;
		FEventContext Context;
		Context.Scripts = &*Scripts;
		Context.MapNumber = Scenario.MapNumber;
		Context.RunningMap = Scenario.MapNumber;
		Context.Zones = Scenario.Zones;
		Context.Walkmesh = &Walkmesh;
		Context.Arctangents = &Arctangents;
		Context.Random = &Random;
		Context.Models = &Models;
		Context.Songs = &Songs;
		Context.SoundEffects = &Sounds;
		Context.GameState = &Game;
		Context.Options = FEventOptions::Original();
		for (uint32 Index = 0; Index < Scenario.Variables.size(); ++Index)
		{
			Context.Variables.Set(Index * 2, Scenario.Variables[Index]);
		}
		for (std::size_t Actor = 0; Actor < Scenario.States.size(); ++Actor)
		{
			const std::span<const uint8> Bytes(Scenario.Records[Actor]);
			FFieldActor& Record = Context.Actors.emplace_back();
			Record.Flags = LittleEndian::ReadU16(Bytes, 0x58);
			for (std::size_t Axis = 0; Axis < 3; ++Axis)
			{
				Record.Translation[Axis] = static_cast<int32>(LittleEndian::ReadU32(Bytes, 0x20 + 4 * Axis));
				Record.Position[Axis] = static_cast<int32>(LittleEndian::ReadU32(Bytes, 0x40 + 4 * Axis));
				Record.Rotation[Axis] = LittleEndian::ReadS16(Bytes, 0x50 + 2 * Axis);
			}
			Context.States.push_back(Testing::FromOriginalLayout(Scenario.States[Actor]));
		}
		Context.PartyActors = Scenario.PartyActors;
		Context.PartyCharacters = Scenario.PartyCharacters;
		Context.LeaderActor = Scenario.Leader;
		Context.PadHeld = Scenario.PadHeld;
		Context.PadLatched = Scenario.PadLatched;
		Context.MovieView = Scenario.bMovieOverField ? EFieldMovieView::OverField : EFieldMovieView::FullScreen;
		Context.bPartyWalking = Scenario.bPartyWalking;
		Context.Clock.Ticks = Scenario.ClockTicks;
		Context.Clock.Mode = Scenario.ClockMode;
		Context.Camera.Eye = Scenario.CameraEye;
		Context.Camera.Target = Scenario.CameraTarget;
		Context.ActorSounds.Channels = Scenario.ActorSoundChannels;
		for (const int32 Actor : Scenario.Resets)
		{
			FEventActorState& State = Context.States[static_cast<std::size_t>(Actor)];
			State.Reset(Random.Next());
			REQUIRE(PlaceActorOnLoad(State, Context.Actors[static_cast<std::size_t>(Actor)], Walkmesh));
		}

		const auto InitError = FEventMachine::InitMap(Context);
		if (InitError)
		{
			FAIL(InitError->Message);
		}
		// The oracle's field runs once the init is over, as after a map's entry: the leader's steps roll encounters.
		Context.bFieldRunning = true;
		FSha1 Hash;
		Hash.Update(Models.Actors);
		AddSnapshot(Hash, Context, Random, Game, Songs, Models, Sounds);
		Context.Render.VramOperations.clear();
		Sounds.Calls.clear();
		for (int32 Tick = 0; Tick < Ticks; ++Tick)
		{
			const auto Error = FEventMachine::Update(Context);
			if (Error)
			{
				FAIL(Error->Message);
			}
			// The frame's steps for the screen wave and the scrollers, as the oracle runs them after the events.
			Context.Render.ScreenWave.Tick();
			Context.Render.TickLineScrolls(Context.Options.bScrollsWrapWithinWidth);
			AddSnapshot(Hash, Context, Random, Game, Songs, Models, Sounds);
			Context.Render.VramOperations.clear();
			Sounds.Calls.clear();
		}
		return FSha1::ToHex(Hash.Finish());
	}
