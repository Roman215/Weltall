	/** A slot's Specials: its character's learned word, each Special's targets and fuel cost. */
	struct FSpecialState
	{
		uint16 Learned = 0;
		std::array<std::array<uint32, 2>, 4> Specials{};
	};

	/** A slot's Ether list: its Ether and gear, its character's gear, the learned words, each ability's cost, targets and bonus. */
	struct FEtherState
	{
		uint8 Ether = 0;
		uint8 Gear = 0;
		uint8 CharacterGear = 0;
		uint16 Learned = 0;
		uint16 GearLearned = 0;
		std::array<std::array<uint32, 3>, EtherEntries> Abilities{};
		std::array<std::array<uint32, 2>, EtherEntries> GearAbilities{};
	};

	FEtherState DrawEtherState(FXorShift32& G)
	{
		FEtherState State;
		State.Ether = static_cast<uint8>(G.Next() & 0xFF);
		State.Gear = static_cast<uint8>(G.Next() % 19);
		State.CharacterGear = static_cast<uint8>(G.Next() % 19);
		State.Learned = static_cast<uint16>(G.Next() & 0xFFFF);
		State.GearLearned = static_cast<uint16>(G.Next() & 0xFFFF);
		for (auto& Ability : State.Abilities)
		{
			Ability[0] = G.Next() % 100;
			Ability[1] = G.Next() & 0xFFFF;
			Ability[2] = G.Next() & 0xFF;
		}
		for (auto& Ability : State.GearAbilities)
		{
			Ability[0] = G.Next() % 100;
			Ability[1] = G.Next() & 0xFFFF;
		}
		return State;
	}

	struct FMember
	{
		uint16 MaxHp = 0;
		uint16 Hp = 0;
		uint16 MaxEp = 0;
		uint16 Ep = 0;
		uint32 GearMax = 0;
		uint32 GearHp = 0;
		uint16 FuelMax = 0;
		uint16 Fuel = 0;
		uint8 StoredAp = 0;
		uint8 InGear = 0;
		bool bSlow = false;
		bool bSpeedUp = false;
		bool bPermanentSpeedUp = false;
	};

	FMember DrawMember(FXorShift32& G)
	{
		FMember Member;
		Member.MaxHp = static_cast<uint16>(G.Next() % 1000);
		Member.MaxEp = static_cast<uint16>(G.Next() % 100);
		Member.GearMax = G.Next() % 100000;
		Member.FuelMax = static_cast<uint16>(1 + G.Next() % 9999);
		Member.Hp = static_cast<uint16>(G.Below(Member.MaxHp + 1u));
		Member.Ep = static_cast<uint16>(G.Below(Member.MaxEp + 1u));
		Member.GearHp = G.Below(Member.GearMax + 1);
		Member.Fuel = static_cast<uint16>(G.Below(Member.FuelMax + 1u));
		Member.StoredAp = static_cast<uint8>(G.Next() % 29);
		Member.InGear = static_cast<uint8>(G.Next() % 3);
		Member.bSlow = G.Next() % 4 == 0;
		Member.bSpeedUp = G.Next() % 4 == 0;
		Member.bPermanentSpeedUp = G.Next() % 8 == 0;
		return Member;
	}

	std::pair<uint16, uint16> DrawWait(FXorShift32& G)
	{
		const uint32 Full = 1 + G.Next() % 300;
		const uint32 Wait = G.Below(Full + 1);
		return {static_cast<uint16>(Wait), static_cast<uint16>(Full)};
	}

	class FRecordedUploads final : public IVramUploads
	{
	public:
		void Upload(const FVramImage& Image) override { Images.push_back(Image); }

		std::vector<FVramImage> Images;
	};

	void Put16(std::vector<uint8>& Bytes, uint32 Value)
	{
		Bytes.push_back(static_cast<uint8>(Value));
		Bytes.push_back(static_cast<uint8>(Value >> 8));
	}

	void Put32(std::vector<uint8>& Bytes, uint32 Value)
	{
		Put16(Bytes, Value);
		Put16(Bytes, Value >> 16);
	}

	/** An upload as the oracle digests it: its tag, its place and size, its units. */
	std::vector<uint8> UploadBytes(const char* Tag, const FVramImage& Image)
	{
		std::vector<uint8> Bytes(Tag, Tag + std::char_traits<char>::length(Tag));
		for (const int16 Value : {Image.Rect.X, Image.Rect.Y, Image.Rect.Width, Image.Rect.Height})
		{
			Put16(Bytes, static_cast<uint16>(Value));
		}
		for (const uint16 Unit : Image.Units)
		{
			Put16(Bytes, Unit);
		}
		return Bytes;
	}

	/**
	 * A case of the "frames" part: the HUD over a random party, drawn with random calls between its frames; of the "menus"
	 * part, with each slot's disabled commands and learned Deathblows, and the party menus' drawing among the calls.
	 */
	class FFramesRun
	{
	public:
		FFramesRun(const FBattleHudResources& Resources, FMesContext& Text, FBattleContext& InContext, FOracleDigest& InDigest, bool bInMenus)
			: Context(InContext), Digest(InDigest), Vram(std::make_unique<FVram>()), Hud(std::make_unique<FBattleHud>(Resources, Text, *Vram, &Recorded)),
			  Names(*Text.Tables), Places(Resources.Tables.Places), bMenus(bInMenus)
		{
		}

		void Run(FXorShift32& G);

	private:
		bool Ended() const { return Hud->Fault() != EBattleHudFault::None; }

		void Chunk(const std::vector<uint8>& Bytes);

		void WriteMember(int32 Slot, const FMember& Member);

		void SetGear(int32 Slot, uint8 InGear);

		void RunOp(FXorShift32& G);

		void RunMenuOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied);

		void RunItemListOp(FXorShift32& G, uint32 Kind);

		void RunEtherListOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied);

		void RunSpecialListOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied);

		void RunComboListOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied);

		void RunAmmunitionOp(FXorShift32& G, uint32 Kind, int32 Slot);

		void RunCockpitOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied);

		/** The Deathblows the Combo command offers the slot, as the turn's code lists them: the learned ones in order with their AP costs. */
		void OfferDeathblows(int32 Slot);

		/** A frame's HUD half as the oracle runs it: the buffer flips, the HUD draws, the battle's input steps its counters. */
		void Frame();

		FBattleContext& Context;
		FOracleDigest& Digest;
		std::unique_ptr<FVram> Vram;
		FRecordedUploads Recorded;
		std::unique_ptr<FBattleHud> Hud;
		const FMesNameTables& Names;
		/** Where the program's run routines put the lists' cursors. */
		const FBattleHudPlaces& Places;
		bool bMenus = false;
		/** The lists' work is made (a first build) and not freed since. */
		bool bListWork = false;
		std::array<uint8, 3> Characters{};
		/** The slots whose cockpit has opened, and with it typed their gear buttons' costs. */
		std::array<bool, 3> bCostsTyped{};
		/** The game's random numbers, which the cockpit's reticle draws from. */
		FPsxRandom Random;
		FBattleHudFrame Drawn;
	};

	void FFramesRun::Run(FXorShift32& G)
	{
		for (int32 Slot = 0; Slot < 3; ++Slot)
		{
			const bool bEmpty = Slot > 0 && G.Next() % 5 == 0;
			Characters[static_cast<std::size_t>(Slot)] = bEmpty ? NoMember : static_cast<uint8>(G.Next() % 11);
		}
		const bool bSpecial = G.Next() % 8 == 0;
		std::array<FMember, 3> Members{};
		for (FMember& Member : Members)
		{
			Member = DrawMember(G);
		}
		std::array<std::pair<uint16, uint16>, 3> Waits{};
		for (auto& Wait : Waits)
		{
			Wait = DrawWait(G);
		}
		FBattleHudSettings Settings;
		for (uint8& Channel : Settings.WindowColour)
		{
			Channel = static_cast<uint8>(G.Next() & 0xFF);
		}
		Settings.WindowBlend = static_cast<uint8>(G.Next() % 4);
		const uint32 Frames = 16 + G.Next() % 65;
		std::array<uint16, 3> Disabled{};
		std::array<uint16, 3> Learned{};
		std::array<FEtherState, 3> Ethers{};
		std::array<FSpecialState, 3> SpecialStates{};
		std::array<std::array<uint8, Deathblows>, 3> ComboCosts{};
		std::array<std::array<uint8, 2>, 2> Ammunition{};
		std::array<std::array<uint8, 2>, 2> GearAmmunition{};
		std::array<uint16, 3> GearAttacks{};
		if (bMenus)
		{
			for (uint16& Mask : Disabled)
			{
				const bool bSome = G.Next() % 2 != 0;
				const uint16 Word = static_cast<uint16>(G.Next() & 0xFFFF);
				Mask = bSome ? Word : 0;
			}
			for (uint16& Word : Learned)
			{
				Word = static_cast<uint16>(G.Next() & 0xFFFF);
			}
			for (std::size_t Cell = 0; Cell < Context.ListedItems.size(); ++Cell)
			{
				const bool bEmpty = G.Next() % 4 == 0;
				const uint8 Item = static_cast<uint8>(1 + G.Next() % 47);
				Context.ListedCounts[Cell] = static_cast<uint8>(G.Next() % 100);
				Context.ListedItems[Cell] = bEmpty ? 0 : Item;
			}
			for (FEtherState& State : Ethers)
			{
				State = DrawEtherState(G);
			}
			for (FSpecialState& State : SpecialStates)
			{
				State.Learned = static_cast<uint16>(G.Next() & 0xFFFF);
				for (auto& Special : State.Specials)
				{
					Special[0] = G.Next() & 0xFFFF;
					Special[1] = G.Next() % 3000;
				}
			}
			for (auto& Costs : ComboCosts)
			{
				for (uint8& Cost : Costs)
				{
					Cost = static_cast<uint8>(G.Next() % 30);
				}
			}
			for (auto* Guns : {&Ammunition, &GearAmmunition})
			{
				for (auto& Gun : *Guns)
				{
					Gun[0] = static_cast<uint8>(G.Next() % 100);
					Gun[1] = static_cast<uint8>(G.Next() & 0xFF);
				}
			}
			for (uint16& Word : GearAttacks)
			{
				Word = static_cast<uint16>(G.Next() & 0xFFFF);
			}
			Random = FPsxRandom(G.Next());
			Context.Random = &Random;
		}

		Context.bSpecialParty = bSpecial;
		for (int32 Slot = 0; Slot < 3; ++Slot)
		{
			const std::size_t At = static_cast<std::size_t>(Slot);
			Context.PartyCharacters[At] = Characters[At];
			Context.Slots[At] = {};
			Context.Slots[At].Occupant = Characters[At];
			Context.Combatants[At] = {};
			WriteMember(Slot, Members[At]);
			Context.Waits[At] = Waits[At].first;
			Context.FullWaits[At] = Waits[At].second;
		}
		if (bMenus)
		{
			// The setup's command menus: each slot's character (whose pictures the HUD gives it) and disabled commands.
			for (int32 Slot = 0; Slot < 3; ++Slot)
			{
				const std::size_t At = static_cast<std::size_t>(Slot);
				FBattleCombatant& Combatant = Context.Combatants[At];
				Combatant.Character = Characters[At] == NoMember ? 0 : Characters[At];
				Combatant.DisabledCommands = Disabled[At];
				for (std::size_t Command = 0; Command < Context.Party.Disabled[At].size(); ++Command)
				{
					Context.Party.Disabled[At][Command] = static_cast<uint16>(Disabled[At] & Context.Program->CommandBits[Command]);
				}
				if (Characters[At] != NoMember)
				{
					LittleEndian::WriteU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize, Learned[At]);
					LittleEndian::WriteU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize + 2, Ethers[At].Learned);
					LittleEndian::WriteU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize + GearAttackSkills, GearAttacks[At]);
					LittleEndian::WriteU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize + 6, Ethers[At].GearLearned);
					Context.GameState->Block()[CharactersOffset + Characters[At] * CharacterSize + CharacterGear] = Ethers[At].CharacterGear;
					LittleEndian::WriteU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize + SpecialSkills, SpecialStates[At].Learned);
				}
				for (int32 Special = 0; Special < 4; ++Special)
				{
					FBattleCommand& Command = Context.Commands[static_cast<std::size_t>(FBattleContext::GearCommandIndex(Slot, FirstSpecial + Special))];
					Command.Targeting = static_cast<uint16>(SpecialStates[At].Specials[static_cast<std::size_t>(Special)][0]);
					Command.FuelCost = static_cast<uint16>(SpecialStates[At].Specials[static_cast<std::size_t>(Special)][1]);
				}
				Combatant.Ether = Ethers[At].Ether;
				Combatant.Gear = Ethers[At].Gear;
				for (int32 Entry = 0; Entry < EtherEntries; ++Entry)
				{
					FBattleCommand& Ability = Context.Commands[static_cast<std::size_t>(FBattleContext::PartyCommandIndex(Slot, FirstAbility + Entry))];
					const auto& Chosen = Ethers[At].Abilities[static_cast<std::size_t>(Entry)];
					Ability.EpCost = static_cast<uint8>(Chosen[0]);
					Ability.Targeting = static_cast<uint16>(Chosen[1]);
					Ability.EtherBonus = static_cast<uint8>(Chosen[2]);
					FBattleCommand& GearAbility = Context.Commands[static_cast<std::size_t>(FBattleContext::GearCommandIndex(Slot, FirstGearAbility + Entry))];
					const auto& GearDrawn = Ethers[At].GearAbilities[static_cast<std::size_t>(Entry)];
					GearAbility.EpCost = static_cast<uint8>(GearDrawn[0]);
					GearAbility.Targeting = static_cast<uint16>(GearDrawn[1]);
				}
				for (int32 Deathblow = 0; Deathblow < Deathblows; ++Deathblow)
				{
					Context.Commands[static_cast<std::size_t>(FBattleContext::PartyCommandIndex(Slot, FirstDeathblow + Deathblow))].ApCost =
						ComboCosts[At][static_cast<std::size_t>(Deathblow)];
				}
			}
			// Billy's two guns' ammunition and what is left of each, on foot and (when he is in the party) in his gear.
			const auto State = Context.GameState->Block();
			const std::size_t Record = CharactersOffset + Billy * CharacterSize;
			for (std::size_t Gun = 0; Gun < Ammunition.size(); ++Gun)
			{
				State[Record + GunAmmunition[Gun]] = Ammunition[Gun][0];
				State[AmmunitionCounts + Ammunition[Gun][0]] = Ammunition[Gun][1];
			}
			if (std::find(Characters.begin(), Characters.end(), Billy) != Characters.end())
			{
				const std::size_t Gear = GearsOffset + State[Record + CharacterGear] * GearSize;
				for (std::size_t Gun = 0; Gun < GearAmmunition.size(); ++Gun)
				{
					State[Gear + GearGunAmmunition[Gun]] = GearAmmunition[Gun][0];
					State[GearAmmunitionCounts + GearAmmunition[Gun][0]] = GearAmmunition[Gun][1];
				}
			}
		}
		Hud->Begin(Context, Settings);
		for (const FVramImage& Image : Recorded.Images)
		{
			Chunk(UploadBytes("setup", Image));
		}
		Recorded.Images.clear();
		Context.Party.InputMode = 2;
		Frame();
		Hud->BeginMessageBoxes();
		if (bMenus)
		{
			Hud->MakeCommandHud();
		}
		Context.Party.InputMode = 1;
		for (uint32 Index = 0; Index < Frames && !Ended(); ++Index)
		{
			const uint32 Ops = G.Next() % 4;
			for (uint32 Op = 0; Op < Ops && !Ended(); ++Op)
			{
				RunOp(G);
			}
			if (!Ended())
			{
				Frame();
			}
		}
		// Where the game writes into a window's block it does not hold, the HUD faults and the case ends, as the oracle's does.
		if (Ended())
		{
			CHECK((Hud->Fault() == EBattleHudFault::WindowNotMade || (bMenus && Hud->Fault() == EBattleHudFault::MessageOutsideTable)));
			Chunk({'u', 'n', 'd', 'e', 'f', 'i', 'n', 'e', 'd'});
		}
	}

	void FFramesRun::Chunk(const std::vector<uint8>& Bytes)
	{
		Digest.Raw(Bytes);
	}

	void FFramesRun::WriteMember(int32 Slot, const FMember& Member)
	{
		FBattleCombatant& Combatant = Context.Combatants[static_cast<std::size_t>(Slot)];
		Combatant.Hp = Member.Hp;
		Combatant.MaxHp = Member.MaxHp;
		Combatant.Ep = Member.Ep;
		Combatant.MaxEp = Member.MaxEp;
		Combatant.Status = static_cast<uint16>((Combatant.Status & ~0x1000) | (Member.bSlow ? 0x1000 : 0));
		Combatant.Buffs = Member.bSpeedUp ? 0x8000 : 0;
		Combatant.PermanentBuffs = Member.bPermanentSpeedUp ? 0x8000 : 0;
		Combatant.GearPart.Fuel = Member.Fuel;
		Combatant.GearPart.MaxFuel = Member.FuelMax;
		Combatant.GearPart.Hp = Member.GearHp;
		Combatant.GearPart.MaxHp = Member.GearMax;
		Context.ApRecords[static_cast<std::size_t>(Slot)].StoredAp = Member.StoredAp;
		SetGear(Slot, Member.InGear);
	}

	void FFramesRun::SetGear(int32 Slot, uint8 InGear)
	{
		Context.ApRecords[static_cast<std::size_t>(Slot)].InGear = InGear;
		Context.Slots[static_cast<std::size_t>(Slot)].InGear = InGear != 0 ? 1 : 0;
	}

	void FFramesRun::RunOp(FXorShift32& G)
	{
		const uint32 Kind = G.Next() % (bMenus ? MenuOps : FrameOps);
		const int32 Slot = static_cast<int32>(G.Next() % 3);
		const bool bOccupied = Characters[static_cast<std::size_t>(Slot)] != NoMember;
		const std::size_t At = static_cast<std::size_t>(Slot);
		switch (Kind)
		{
		case 0:
		{
			FMember Member = DrawMember(G);
			Member.InGear = Context.ApRecords[At].InGear;
			WriteMember(Slot, Member);
			Context.PanelRefresh[At] = 1;
			break;
		}
		case 1:
		{
			const auto [Wait, Full] = DrawWait(G);
			Context.Waits[At] = Wait;
			Context.FullWaits[At] = Full;
			break;
		}
		case 2:
		{
			bool bResting = true;
			for (const uint8 Icon : Context.Party.TurnIcons)
			{
				bResting = bResting && (Icon == 0 || Icon == 1);
			}
			if (bOccupied && bResting && Context.Party.InputMode == 1)
			{
				Context.Party.TurnIcons[At] = 3;
			}
			break;
		}
		case 3:
			Context.Party.TurnIcons[At] = 0;
			break;
		case 4:
			if (bOccupied)
			{
				Hud->StartActorFlash(static_cast<uint8>(Slot));
			}
			break;
		case 5:
			Hud->StopActorFlash();
			break;
		case 6:
		{
			const int32 Box = static_cast<int32>(G.Next() % 8);
			Hud->TypeMessageBox(Box, Names.String(ItemNames, static_cast<int32>(G.Next() % 200)));
			break;
		}
		case 7:
			Hud->ShowMessageBox(static_cast<int32>(G.Next() % 8));
			break;
		case 8:
			Hud->HideMessageBox(static_cast<int32>(G.Next() % 8));
			break;
		case 9:
			Hud->HideMessageBoxes();
			Frame();
			break;
		case 10:
		{
			const int32 Window = MenuWindows[G.Next() % MenuWindows.size()];
			const int16 X = static_cast<int16>(8 + G.Next() % 200);
			const int16 Y = static_cast<int16>(8 + G.Next() % 150);
			const uint16 Width = static_cast<uint16>(0x20 + G.Next() % 0xC0);
			const uint16 Height = static_cast<uint16>(0x18 + G.Next() % 0x60);
			const bool bGrows = G.Next() % 2 != 0;
			Hud->OpenWindow(Window, X, Y, Width, Height, bGrows);
			break;
		}
		case 11:
		{
			const int32 Window = MenuWindows[G.Next() % MenuWindows.size()];
			if (Hud->WindowShown(Window) || Hud->WindowGrowing(Window))
			{
				Hud->CloseWindow(Window);
				Frame();
			}
			break;
		}
		case 12:
		{
			const uint8 Mode = static_cast<uint8>(1 + G.Next() % 2);
			bool bResting = true;
			for (const uint8 Icon : Context.Party.TurnIcons)
			{
				bResting = bResting && (Icon == 0 || Icon == 1);
			}
			if (Mode == 1 || bResting)
			{
				Context.Party.InputMode = Mode;
			}
			break;
		}
		case 13:
			Hud->SetHidden(G.Next() % 2 != 0);
			break;
		case 14:
			Hud->ShowNameBox(Names.String(ItemNames, static_cast<int32>(G.Next() % 200)));
			break;
		case 15:
			if (bOccupied)
			{
				SetGear(Slot, 2);
				Hud->BoardGear(static_cast<uint8>(Slot));
				Context.PanelRefresh[At] = 1;
			}
			break;
		case 16:
		{
			const uint8 AtStart = static_cast<uint8>(3 + G.Next() % 5);
			Hud->ShowApTicks(AtStart, static_cast<uint8>(G.Next() % (AtStart + 1u)));
			break;
		}
		case 17:
		{
			const uint8 AtStart = static_cast<uint8>(3 + G.Next() % 5);
			Hud->DrawApNumbers(static_cast<uint8>(G.Next() % (AtStart + 1u)), AtStart);
			break;
		}
		case 18:
			Hud->ShowApNumbers(G.Next() % 2 != 0);
			break;
		default:
			RunMenuOp(G, Kind, Slot, bOccupied);
			break;
		}
	}

	void FFramesRun::RunMenuOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied)
	{
		FBattlePartyInput& Party = Context.Party;
		const uint8 At = static_cast<uint8>(Slot);
		switch (Kind)
		{
		case 19:
		{
			const uint8 State = MenuStates[G.Next() % MenuStates.size()];
			const bool bFading = G.Next() % 4 == 0;
			// A gear's attack mode is drawn only once the slot's cockpit has typed the buttons' costs.
			if (bOccupied && (State != 0x19 || bCostsTyped[At]))
			{
				Party.MenuState = State;
				Party.bMenuFading = bFading;
				Party.bIconsShown = false;
				Hud->DrawCommandIcons(At);
				Party.bIconsShown = true;
			}
			break;
		}
		case 20:
			Hud->InitDirectionArrows();
			break;
		case 21:
			Hud->HideDirectionArrows();
			break;
		case 22:
			Hud->SetArrowTargets(static_cast<uint8>(G.Next() % 16));
			break;
		case 23:
		{
			const uint32 Count = 1 + G.Next() % 7;
			std::array<uint8, FBattlePartyInput::MaxButtons> Buttons{};
			Buttons.fill(0xFF);
			for (uint32 Press = 0; Press < Count; ++Press)
			{
				Buttons[Press] = AttackButtons[G.Next() % AttackButtons.size()];
			}
			const bool bDeathblow = G.Next() % 4 == 0;
			uint32 Pressed = Count;
			if (G.Next() % 2 == 0)
			{
				// One of the program's patterns, then the Fierce finisher when the Deathblow flag is drawn.
				const auto& Pattern = Context.Program->Patterns[G.Next() % FBattleProgramTables::PatternCount];
				Buttons.fill(0xFF);
				Pressed = 0;
				for (const uint8 Button : Pattern)
				{
					if (Button != 0xFF)
					{
						Buttons[Pressed++] = Button;
					}
				}
				if (bDeathblow)
				{
					Buttons[Pressed++] = 0;
				}
			}
			if (bOccupied)
			{
				Party.Buttons = Buttons;
				Party.ButtonCount = static_cast<uint8>(Pressed);
				Party.Deathblow = bDeathblow ? 1 : 0;
				Hud->DrawDeathblowHints(At);
				if (!Ended())
				{
					Frame();
				}
			}
			break;
		}
		case 24:
			Hud->CloseCommandHud();
			if (Context.ApRecords[At].InGear == 2)
			{
				Context.ApRecords[At].InGear = 1;
			}
			Hud->MakeCommandHud();
			break;
		case 25:
			Hud->HideApNumbers();
			break;
		default:
			if (Kind <= 32)
			{
				RunItemListOp(G, Kind);
			}
			else
			{
				RunEtherListOp(G, Kind, Slot, bOccupied);
			}
			break;
		}
	}

	void FFramesRun::RunEtherListOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied)
	{
		FBattlePartyInput& Party = Context.Party;
		const uint8 At = static_cast<uint8>(Slot);
		switch (Kind)
		{
		case 33:
			for (int32 Window = 0; Window < EtherWindows; ++Window)
			{
				Hud->OpenListWindow(EBattleMenuList::Ether, Window);
				Frame();
			}
			break;
		case 34:
			if (bOccupied)
			{
				Hud->BuildEtherList(At);
				bListWork = true;
				Frame();
				if (!Ended())
				{
					Hud->ShowEtherCells();
					Party.ListWindow = 1;
				}
			}
			break;
		case 35:
		{
			const uint8 Cell = static_cast<uint8>(G.Next() % 12);
			const uint8 Row = static_cast<uint8>(G.Next() % 3);
			if (bOccupied && bListWork)
			{
				Hud->DrawEtherInfo(At, Cell, Row);
			}
			break;
		}
		case 36:
		{
			const int32 Scroll = static_cast<int32>(G.Next() % 33);
			if (bListWork)
			{
				Hud->DrawEtherThumb(Scroll);
				Hud->SetEtherCells(Scroll);
			}
			break;
		}
		case 37:
		{
			const int32 Cell = static_cast<int32>(G.Next() % 12);
			Hud->DrawListCursor(static_cast<int16>((Cell & 1) != 0 ? 0xAE : 0x2A), static_cast<int16>((Cell >> 1) * 16 + Places.EtherCursorY));
			break;
		}
		case 38:
		{
			const bool bShow = G.Next() % 2 != 0;
			const bool bLeft = G.Next() % 2 == 0;
			bool bMade = true;
			for (int32 Window = 0; Window < EtherWindows; ++Window)
			{
				bMade = bMade && Hud->WindowMade(Window);
			}
			if (bShow && bListWork && bMade)
			{
				Hud->ShowListWindows(EBattleMenuList::Ether);
				Party.ListWindow = 1;
			}
			else if (!bShow)
			{
				Hud->HideListWindows(EBattleMenuList::Ether);
				Party.ListWindow = 0;
				if (bLeft)
				{
					Party.bIconsShown = true;
				}
			}
			break;
		}
		default:
			RunSpecialListOp(G, Kind, Slot, bOccupied);
			break;
		}
	}

