	void FFramesRun::OfferDeathblows(int32 Slot)
	{
		const std::size_t At = static_cast<std::size_t>(Slot);
		FBattleComboMenu& Combo = Context.Party.Combo;
		Combo.Offered.fill(0xFF);
		Combo.Costs.fill(0);
		const uint16 Learned = LittleEndian::ReadU16(Context.GameState->Block(), LearnedSkills + Characters[At] * LearnedSkillsSize);
		std::size_t Offered = 0;
		for (int32 Deathblow = 0; Deathblow < Deathblows; ++Deathblow)
		{
			if ((Learned & (0x8000u >> Deathblow)) != 0)
			{
				Combo.Offered[Offered] = static_cast<uint8>(Deathblow);
				Combo.Costs[Offered] = Context.Commands[static_cast<std::size_t>(FBattleContext::PartyCommandIndex(Slot, FirstDeathblow + Deathblow))].ApCost;
				++Offered;
			}
		}
	}

	void FFramesRun::RunComboListOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied)
	{
		FBattlePartyInput& Party = Context.Party;
		const uint8 At = static_cast<uint8>(Slot);
		switch (Kind)
		{
		case 44:
			for (int32 Window = 0; Window < ComboWindows; ++Window)
			{
				Hud->OpenListWindow(EBattleMenuList::Combo, Window);
			}
			break;
		case 45:
			if (bOccupied)
			{
				OfferDeathblows(Slot);
				Hud->BuildComboList(At);
				bListWork = true;
				Party.ListWindow = 3;
			}
			break;
		case 46:
		{
			const uint32 Queued = G.Next() % 8;
			std::array<uint8, FBattlePartyInput::MaxButtons> Cells{};
			for (uint8& Cell : Cells)
			{
				Cell = static_cast<uint8>(G.Next() % 8);
			}
			const uint8 Pool = static_cast<uint8>(G.Next() % 29);
			if (bListWork)
			{
				for (uint32 Place = 0; Place < Party.ComboQueue.size(); ++Place)
				{
					Party.ComboQueue[Place] = Place < Queued ? static_cast<uint8>(Place) : 0xFF;
				}
				Party.ComboCells = Cells;
				Hud->DrawComboQueue(Pool);
			}
			break;
		}
		case 47:
		{
			const int32 Cell = static_cast<int32>(G.Next() % 8);
			Hud->DrawListCursor(static_cast<int16>((Cell & 1) != 0 ? 0xAA : 0x1E), static_cast<int16>((Cell >> 1) * 16 + 100));
			break;
		}
		case 48:
		{
			const bool bShow = G.Next() % 2 != 0;
			const bool bClose = G.Next() % 2 != 0;
			if (bShow)
			{
				if (bListWork && Hud->WindowMade(0) && Hud->WindowMade(1))
				{
					Hud->ShowListWindows(EBattleMenuList::Combo);
					Party.ListWindow = 3;
				}
			}
			else if (!bClose)
			{
				Hud->HideListWindows(EBattleMenuList::Combo);
				Party.ListWindow = 0;
			}
			else if (bListWork)
			{
				// The list closes: its sprites hidden, each window closed a frame, a frame, the work's frame.
				Hud->HideComboList();
				Party.ListWindow = 0;
				for (int32 Window = 0; Window < ComboWindows; ++Window)
				{
					Hud->CloseWindow(Window);
					Frame();
				}
				Frame();
				Frame();
				Hud->FreeListWork();
				bListWork = false;
				Hud->HideDirectionArrows();
			}
			break;
		}
		default:
			RunAmmunitionOp(G, Kind, Slot);
			break;
		}
	}

	void FFramesRun::RunAmmunitionOp(FXorShift32& G, uint32 Kind, int32 Slot)
	{
		FBattlePartyInput& Party = Context.Party;
		// The party's Billy, when it has one.
		const auto Found = std::find(Characters.begin(), Characters.end(), Billy);
		const uint8 At = Found != Characters.end() ? static_cast<uint8>(Found - Characters.begin()) : static_cast<uint8>(Slot);
		const bool bBilly = Characters[At] == Billy;
		if (Kind == 49)
		{
			if (bBilly && Party.ListWindow == 0)
			{
				Hud->BuildAmmunition(At);
				bListWork = true;
				Frame();
				if (!Ended())
				{
					Party.ListWindow = 5;
					Party.bAmmunitionShown = true;
				}
			}
			return;
		}
		if (Kind != 50)
		{
			RunCockpitOp(G, Kind, Slot, Characters[static_cast<std::size_t>(Slot)] != NoMember);
			return;
		}
		const bool bClose = G.Next() % 2 != 0;
		if (!bBilly)
		{
			return;
		}
		Party.ListWindow = 0;
		Hud->HideAmmunition();
		if (bClose && Party.bAmmunitionShown)
		{
			Hud->CloseWindow(0);
			Frame();
			Frame();
			Hud->FreeListWork();
			bListWork = false;
			Party.bAmmunitionShown = false;
		}
	}

	void FFramesRun::RunItemListOp(FXorShift32& G, uint32 Kind)
	{
		FBattlePartyInput& Party = Context.Party;
		switch (Kind)
		{
		case 26:
			for (int32 Window = 0; Window < 2; ++Window)
			{
				Hud->OpenListWindow(EBattleMenuList::Items, Window);
				Frame();
			}
			break;
		case 27:
			Hud->BuildItemList(!bListWork);
			bListWork = true;
			Frame();
			if (!Ended())
			{
				Hud->ShowListCells();
				Party.ListWindow = 2;
			}
			break;
		case 28:
		{
			const uint8 Cell = static_cast<uint8>(G.Next() % 16);
			const uint8 Row = static_cast<uint8>(G.Next() % 17);
			if (bListWork)
			{
				Hud->DrawItemInfo(Cell, Row);
			}
			break;
		}
		case 29:
		{
			const int32 Scroll = 13 * static_cast<int32>(G.Next() % 17);
			if (bListWork)
			{
				Hud->DrawItemThumb(Scroll / 13 * 2);
				Hud->SetItemCells(Scroll);
			}
			break;
		}
		case 30:
		{
			const int32 Cell = static_cast<int32>(G.Next() % 16);
			const int32 Odd = Cell & 1;
			Hud->DrawListCursor(static_cast<int16>(Odd << 7 | (Odd * 2 + 0x2A)), static_cast<int16>((Cell >> 1) * 13 + Places.ItemCursorY));
			break;
		}
		case 31:
		{
			const bool bShow = G.Next() % 2 != 0;
			const bool bLeft = G.Next() % 2 == 0;
			if (bShow && bListWork && Hud->WindowMade(0) && Hud->WindowMade(1))
			{
				Hud->ShowListWindows(EBattleMenuList::Items);
				Party.ListWindow = 2;
			}
			else if (!bShow)
			{
				Hud->HideListWindows(EBattleMenuList::Items);
				Party.ListWindow = 0;
				if (bLeft)
				{
					Party.bIconsShown = true;
				}
			}
			break;
		}
		case 32:
			if (bListWork && Party.ListWindow == 0)
			{
				Frame();
				Hud->FreeListWork();
				bListWork = false;
			}
			break;
		}
	}

	void FFramesRun::RunCockpitOp(FXorShift32& G, uint32 Kind, int32 Slot, bool bOccupied)
	{
		FBattlePartyInput& Party = Context.Party;
		const uint8 At = static_cast<uint8>(Slot);
		switch (Kind)
		{
		case 51:
		{
			FBattleGearTurn Turn;
			for (uint16& Cost : Turn.Costs)
			{
				Cost = static_cast<uint16>(G.Next() % 1000);
			}
			Turn.ShownAttack = static_cast<uint16>(G.Next() % 10000);
			Turn.Lamps = static_cast<uint16>(G.Next() & 0xF800);
			Turn.Level = static_cast<uint8>(G.Next() % 5);
			Turn.Agility = static_cast<uint8>(G.Next() & 0xFF);
			Turn.ArmorBreak = static_cast<uint8>(G.Next() & 0xFF);
			Turn.bBooster = G.Next() % 2 != 0;
			Turn.InfinityChance = static_cast<uint8>(G.Next() % 100);
			if (!bOccupied)
			{
				break;
			}
			// The turn before closes its command HUD; the gear's turn opens the cockpit over two frames.
			Context.GearTurn = Turn;
			Hud->CloseCommandHud();
			if (Context.ApRecords[At].InGear == 2)
			{
				Context.ApRecords[At].InGear = 1;
			}
			Hud->OpenCockpit(At);
			bCostsTyped[At] = true;
			if (Characters[At] == ChuChu)
			{
				break;
			}
			Frame();
			if (!Ended())
			{
				Hud->DrawCockpitFuel(At);
				Frame();
			}
			if (!Ended())
			{
				Hud->ShowCockpit();
			}
			break;
		}
		case 52:
			if (bOccupied)
			{
				Hud->DrawCockpitFuel(At);
			}
			break;
		case 53:
			Hud->HideCockpit();
			break;
		default:
		{
			const uint8 Level = Context.GearTurn.Level;
			const bool bOpening = G.Next() % 8 == 0 && Level == InfinityLevel;
			uint8 Button = static_cast<uint8>(G.Next() % 3);
			const uint8 Count = static_cast<uint8>(G.Next() % 3);
			const std::array<uint8, 2> Pressed{static_cast<uint8>(G.Next() % 3), static_cast<uint8>(G.Next() % 3)};
			const uint8 Deathblow = Count != 0 ? static_cast<uint8>(G.Next() % 2) : 0;
			uint8 Hits = static_cast<uint8>(G.Next() % 3);
			const bool bTargetInGear = G.Next() % 4 != 0;
			if (bOpening)
			{
				Button = NoButton;
				Hits = Hits == 0 ? 1 : Hits;
			}
			if (!bOccupied)
			{
				break;
			}
			Context.SlotTargets[At] = GearTarget;
			uint8& Flags = Context.Combatants[GearTarget].BattleFlags;
			Flags = static_cast<uint8>((Flags & 0x7F) | (bTargetInGear ? 0x80 : 0));
			Party.Buttons.fill(0xFF);
			std::copy_n(Pressed.begin(), Count, Party.Buttons.begin());
			Party.ButtonCount = Count;
			Party.Deathblow = Deathblow;
			Party.GearHits = Hits;
			// The press is recorded, and its hints drawn, against a target in a gear or at the Infinity level, unless it is a first press the level does not reach.
			if (!bTargetInGear && Level != InfinityLevel)
			{
				break;
			}
			if ((Level == 0 || static_cast<int32>(Level) - 1 < static_cast<int32>(Button)) && Hits == 0)
			{
				break;
			}
			Party.Buttons[Party.ButtonCount] = Button;
			++Party.ButtonCount;
			Hud->DrawGearHints(At, Button);
			if (!Ended())
			{
				Frame();
			}
			break;
		}
		}
	}

	void FFramesRun::Frame()
	{
		Hud->Flip();
		Hud->Draw(Drawn);
		if (Ended())
		{
			return;
		}
		FMenuFrame Packets;
		Packets.Primitives = Drawn.Primitives;
		Chunk(Testing::CanonicalMenuPackets(Packets));
		if (Context.Party.InputMode == 1)
		{
			Hud->StepMenuInput();
		}
		for (const FVramImage& Image : Recorded.Images)
		{
			Chunk(UploadBytes("upload", Image));
		}
		Recorded.Images.clear();
		std::vector<uint8> Counters = {Hud->IconSteps(), Hud->TextureStep(), Hud->IconGrowth()};
		Put32(Counters, Hud->TextureRow());
		Put32(Counters, static_cast<uint32>(Hud->FlashLevel()));
		Counters.push_back(Hud->FlashFalling() ? 1 : 0);
		Counters.insert(Counters.end(), Context.Party.TurnIcons.begin(), Context.Party.TurnIcons.end());
		Counters.insert(Counters.end(), Context.PanelRefresh.begin(), Context.PanelRefresh.begin() + 3);
		if (bMenus)
		{
			Put32(Counters, Random.Seed());
		}
		Chunk(Counters);
	}
